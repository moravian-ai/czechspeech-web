// Generates src/worklet.js: the AudioWorklet module of listen() as one self-contained file (src/resampler.js +
// scripts/worklet-processor.js, without imports or exports). Bundlers copy a worklet referenced through
// `new URL('./worklet.js', import.meta.url)` as a static asset and do not follow its imports, so it must not have any.
//
// Usage: node scripts/build-worklet.mjs [--check]   (--check: exit 1 when src/worklet.js is out of date)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8').replace(/\r\n/g, '\n');

export function generateWorklet() {
  const resampler = read('src/resampler.js').replace(/^export (const|class|function) /gm, '$1 ');
  const processor = read('scripts/worklet-processor.js').replace(/^import .*\n/gm, '');
  if (/^\s*(import|export)\b/m.test(resampler + processor)) throw new Error('imports/exports left in the worklet');
  return '// GENERATED by scripts/build-worklet.mjs from src/resampler.js and scripts/worklet-processor.js; do not edit.\n\n' +
    resampler.trimEnd() + '\n\n' + processor.trimEnd() + '\n';
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const out = path.join(root, 'src/worklet.js');
  const text = generateWorklet();
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
    if (current !== text) {
      console.error('src/worklet.js is out of date: run node scripts/build-worklet.mjs');
      process.exit(1);
    }
    console.log('src/worklet.js is up to date');
  } else {
    fs.writeFileSync(out, text);
    console.log(`src/worklet.js: ${text.length} bytes`);
  }
}
